export const isNewChangelogEntry = (entry, now = new Date()) => {
  const today = Date.UTC(now.getUTCFullYear(), now.getUTCMonth(), now.getUTCDate());
  const entryDate = Date.parse(`${entry.date}T00:00:00Z`);
  const ageInDays = (today - entryDate) / 86400000;

  return ageInDays >= 0 && ageInDays <= 7;
};
